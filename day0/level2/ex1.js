// Grading System: Declare a variable score (0-100). Use if/else if/else statements to log "A" for 90-100, "B" for 80-89, "C" for 70-79, and "F" for anything below 70.

let num = 80 ; 

if(num >= 90 && num <= 100){
    console.log("A");
}
else if(num >= 80 && num <= 89){
    console.log("B");

}
else if(num >= 70 && num <= 79){
    console.log("C");

}
else {
    console.log("F")
}